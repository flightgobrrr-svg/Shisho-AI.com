/** The picker's display name for a state; English is the key itself. */
export function stateLabel(copy: StatePickerCopy, state: StateName): string {
  return copy.states?.[state] ?? state;
}

/** The picker's display name for a court; English is the legal name itself. */
export function courtLabel(copy: StatePickerCopy, court: string): string {
  return copy.courts?.[court as CourtName] ?? court;
}
