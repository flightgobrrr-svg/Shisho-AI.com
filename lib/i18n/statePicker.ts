/**
 * The state / union-territory picker (components/map/StateSelect.tsx) in each
 * homepage language: the question, the groups, all 36 names, the line under
 * the box, and the answer — which High Court has writ jurisdiction.
 *
 * Court names. In English the picker uses each court's current legal name,
 * old city names included (Bombay, Madras, Calcutta, Allahabad, Gauhati,
 * Orissa), and lib/states.ts deliberately does not "correct" them. Here each
 * court is written the way that language's legal writing names it — mostly a
 * transliteration of the legal name, plus that language's own word for High
 * Court, matching the word the rest of its dictionary already uses — with
 * three courts given the name their home language actually uses for them:
 * मुंबई उच्च न्यायालय in Marathi, சென்னை உயர் நீதிமன்றம் in Tamil, and
 * কলকাতা হাইকোর্ট in Bengali. Because a filing is drafted in English, the
 * picker also prints the English legal name beside the translated one, so the
 * name an advocate has to write is never something a reader must guess back.
 *
 * The answer is a label and the court ("रिट क्षेत्राधिकार: बॉम्बे उच्च
 * न्यायालय") rather than a sentence around it: in Tamil, Telugu, Kannada,
 * Malayalam, Marathi and Bengali a sentence would inflect the court name with
 * a case suffix, i.e. 36 more forms per language to get wrong.
 *
 * Numerals follow each dictionary: Bengali and Marathi write their own digits
 * there, the other languages write 0–9, and this file does the same.
 *
 * The same caveat as dictionaries.ts applies: these are careful translations,
 * not native-speaker-reviewed ones, and should get that review before launch.
 */
